_FONT_WIDTH = 5
_FONT_HEIGHT = 7
_BLANK = ("00000",) * 7


def glyph_rows(char):
    """Return the seven 5-bit rows for a character (blank if unknown)."""
    return _GLYPHS.get(char.upper(), _BLANK)


def char_advance(scale):
    """Horizontal step per character at the given scale."""
    return (_FONT_WIDTH + 1) * scale


def text_width(text, scale):
    """Pixel width of a string at the given scale (no trailing gap)."""
    if not text:
        return 0
    return len(text) * char_advance(scale) - scale


def wrap_text(text, max_width, scale):
    """Greedy word wrap. Returns a list of lines that fit max_width."""
    words = text.split()
    lines = []
    current = ""
    for word in words:
        trial = word if not current else current + " " + word
        if text_width(trial, scale) <= max_width:
            current = trial
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


# --------------------------------------------------------------------------
# Canvas
# --------------------------------------------------------------------------

class Canvas:
    """A plain RGB canvas backed by a bytearray."""

    def __init__(self, width, height, background):
        self.width = width
        self.height = height
        self.pixels = bytearray(background * (width * height))

    def set_pixel(self, x, y, color):
        if 0 <= x < self.width and 0 <= y < self.height:
            offset = (y * self.width + x) * 3
            self.pixels[offset:offset + 3] = bytes(color)

    def fill_rect(self, x, y, w, h, color):
        """Fill an axis-aligned rectangle, clipped to the canvas."""
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(self.width, x + w)
        y1 = min(self.height, y + h)
        if x1 <= x0 or y1 <= y0:
            return
        row = bytes(color) * (x1 - x0)
        for yy in range(y0, y1):
            offset = (yy * self.width + x0) * 3
            self.pixels[offset:offset + len(row)] = row

    def hline(self, x, y, w, color):
        self.fill_rect(x, y, w, 1, color)

    def vline(self, x, y, h, color):
        self.fill_rect(x, y, 1, h, color)

    def draw_text(self, text, x, y, scale, color):
        """Draw text with its top-left corner at (x, y). Returns end x."""
        cursor = x
        for char in text:
            rows = glyph_rows(char)
            for row_index, bits in enumerate(rows):
                for col_index, bit in enumerate(bits):
                    if bit == "1":
                        self.fill_rect(
                            cursor + col_index * scale,
                            y + row_index * scale,
                            scale, scale, color,
                        )
            cursor += char_advance(scale)
        return cursor

    def draw_text_centered(self, text, center_x, y, scale, color):
        """Draw text centered on center_x. Returns the left edge used."""
        left = center_x - text_width(text, scale) // 2
        self.draw_text(text, left, y, scale, color)
        return left


# --------------------------------------------------------------------------
# PNG writer
# --------------------------------------------------------------------------

def _png_chunk(kind, payload):
    size = struct.pack(">I", len(payload))
    crc = struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
    return size + kind + payload + crc


def save_png(canvas, path):
    """Encode the canvas as a deterministic 8-bit RGB PNG file."""
    scanlines = bytearray()
    row_bytes = canvas.width * 3
    for y in range(canvas.height):
        scanlines.append(0)  # filter type 0: none
        start = y * row_bytes
        scanlines += canvas.pixels[start:start + row_bytes]
    ihdr = struct.pack(">IIBBBBB", canvas.width, canvas.height, 8, 2, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n"
    png += _png_chunk(b"IHDR", ihdr)
    png += _png_chunk(b"IDAT", zlib.compress(bytes(scanlines), 9))
    png += _png_chunk(b"IEND", b"")
    with open(path, "wb") as handle:
        handle.write(png)
